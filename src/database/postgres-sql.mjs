// The repositories share SQL with SQLite. Keep the dialect differences here,
// while leaving storage algorithms, transaction boundaries and bindings in
// the repositories. All input is repository SQL. User values stay parameters.
const TOKEN = /'(?:''|[^'])*'|"(?:""|[^"])*"|--[^\n]*|\/\*[\s\S]*?\*\/|[a-z_][\w]*|[^\s]|\s+/gi;

function tokens(sql) {
  return [...sql.matchAll(TOKEN)].map(([token]) => token);
}

export function statements(sql) {
  const result = [];
  let statement = '';
  for (const token of tokens(sql)) {
    if (token === ';') {
      if (statement.trim()) result.push(statement.trim());
      statement = '';
    } else if (!token.startsWith('--') && !token.startsWith('/*')) {
      statement += token;
    }
  }
  if (statement.trim()) result.push(statement.trim());
  return result;
}

function translateFunctions(sql) {
  const parts = tokens(sql);
  const calls = [];
  let last = -1;
  for (const [index, token] of parts.entries()) {
    if (!token.trim()) continue;
    if (token === '(') calls.push(last);
    if (token === ')') {
      const call = calls.pop();
      if (/^json_object$/i.test(parts[call])) {
        parts[call] = 'json_build_object';
        parts[index] += '::text';
      }
    }
    if (token === ',') {
      const call = calls.at(-1);
      if (/^min$/i.test(parts[call])) parts[call] = 'LEAST';
      if (/^max$/i.test(parts[call])) parts[call] = 'GREATEST';
    }
    last = index;
  }
  return parts.join('');
}

export function postgresSql(sql) {
  const columns = /^(?:SELECT name FROM pragma_table_info\(([^)]+)\)|PRAGMA table_info\((\w+)\))$/i.exec(sql);
  if (columns) {
    sql = 'SELECT column_name AS name FROM information_schema.columns '
      + `WHERE table_schema = current_schema() AND table_name = ${columns[1] ?? `'${columns[2]}'`} ORDER BY ordinal_position`;
  }
  sql = sql
    .replace(/\bsqlite_master WHERE type = 'table'/gi, "information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' AND table_name <> 'pictaria_schema_version'")
    .replace(/(table_type = 'BASE TABLE' AND table_name <> 'pictaria_schema_version') AND name =/gi, '$1 AND table_name =')
    .replace(/^BEGIN (IMMEDIATE|EXCLUSIVE)$/i, 'BEGIN')
    .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bWITHOUT ROWID\b/gi, '')
    .replace(/\s+INDEXED BY \w+/gi, '')
    .replace(/\bCAST\(([\w.]+) AS BLOB\)/gi, "convert_to($1::text, 'UTF8')")
    .replace(/\btypeof\(([\w.]+)\)/gi, "(CASE WHEN $1 IS NULL THEN 'null' WHEN pg_typeof($1) = 'bigint'::regtype THEN 'integer' ELSE 'text' END)")
    .replace(/\bjson_extract\(([^,]+),\s*('(\$\.(?:[\w.]+))')\)/gi, (call, source, path, key) =>
      /(?:\.expiresAt|\.has_people|\.preparationFailures|\.formatVersion|\.contractVersion)$/.test(key)
        && !key.includes('.properties.') ? `pictaria_json_number(${source}, ${path})` : call)
    .replace(/\bjson_array_length\(([\w.]+)\)/gi, 'json_array_length($1::json)')
    .replace(/\bjson_each\(([^)]+)\)/gi, 'json_array_elements_text($1::json)')
    .replace(/\bprintf\('%020d', (\w+)\)/gi, "lpad($1::text, 20, '0')")
    .replace(/\b([\w.]+) COLLATE NOCASE\b/gi, 'lower($1)')
    .replace(/\bIS (NOT )?(?=[a-z_]+\.)/gi, (_, not) => not ? 'IS DISTINCT FROM ' : 'IS NOT DISTINCT FROM ')
    .replace(/\bCASE WHEN \? THEN\b/gi, 'CASE WHEN ?::bigint <> 0 THEN')
    .replace(/\bWHERE 0\b/gi, 'WHERE FALSE')
    .replace(/\b(key) (NOT )?GLOB (\?|'[^']*\*')/gi, (_, key, not, pattern) =>
      `starts_with(${key}, left(${pattern}::text, -1)) IS ${not ? 'FALSE' : 'TRUE'}`)
    .replace(/\bSELECT rowid,/gi, 'SELECT ctid AS rowid,')
    .replace(/(?<!AS )\browid\b/gi, 'ctid')
    .replace(/\bCAST\(([^()]+) AS REAL\)/gi, 'CAST($1 AS DOUBLE PRECISION)')
    .replace(/\b(INTEGER|REAL|BLOB)(?=\s*(?:,|\)|NOT NULL|DEFAULT|PRIMARY KEY|CHECK|REFERENCES))/gi, (type) =>
      ({ INTEGER: 'BIGINT', REAL: 'DOUBLE PRECISION', BLOB: 'BYTEA' })[type.toUpperCase()]);
  let parameter = 0;
  return tokens(translateFunctions(sql)).map((token) => {
    if (token === '?') return `$${++parameter}`;
    return token;
  }).join('');
}
